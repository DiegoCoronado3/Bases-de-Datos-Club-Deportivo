CREATE TABLE OPERACION.INSTALACION (
    ID_INSTALACION VARCHAR(20) PRIMARY KEY,
    NOMBRE_INSTALACION VARCHAR(100) NOT NULL,
    CAPACIDAD INT,
    DESCRIPCION VARCHAR(MAX)
