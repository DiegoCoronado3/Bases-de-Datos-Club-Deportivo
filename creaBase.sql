-- TABLA 10: MATERIAL
-- Descripción: Catálogo global de materiales.
CREATE TABLE OPERACION.MATERIAL (
    ID_MATERIAL VARCHAR(20) PRIMARY KEY, 
    DESCRIPCION VARCHAR(50),
    UNIDADES_TOTALES INT
);

-- TABLA 11: DIETA
-- Descripción: Asignación de dietas a usuarios.
CREATE TABLE OPERACION.DIETA (
    ID_DIETA INT PRIMARY KEY IDENTITY(1,1),
    ID_USUARIO INT,
    ID_PLATILLO INT,
    DIA_SEMANA VARCHAR(15),
    CALORIAS_TOTALES INT,
    CONSTRAINT FK_Dieta_Socio FOREIGN KEY (ID_USUARIO) REFERENCES MEMBRESIA.SOCIO(ID_USUARIO),
    CONSTRAINT FK_Dieta_Plat FOREIGN KEY (ID_PLATILLO) REFERENCES OPERACION.PLATILLO(ID_PLATILLO)
);

-- TABLA 12: SERVICIOS_ACTIVIDADES
-- Descripción: Catálogo de clases y servicios.
-- Regla: Edad mínima por default 16 años.
CREATE TABLE OPERACION.SERVICIOS_ACTIVIDADES (
    ID_SERVICIO_ACTIVIDAD INT PRIMARY KEY IDENTITY(1,1),
    NOMBRE_ACTIVIDAD VARCHAR(100) NOT NULL,
    DESCRIPCION VARCHAR(MAX),
    TIPO_ACTIVIDAD VARCHAR(20), 
    
    -- Consideración: Uso de VALOR POR DEFAULT
    EDAD_MINIMA INT DEFAULT 16, 
    
    CONSTRAINT CK_TipoActividad CHECK (TIPO_ACTIVIDAD IN ('CUOTA', 'GRATUITA', 'CULTURAL')),
    CONSTRAINT CK_EdadMinimaActividad CHECK (EDAD_MINIMA >= 16)
);



-- TABLA 13: CUOTA
-- Descripción: Subtipo de actividad que requiere pago.
CREATE TABLE OPERACION.CUOTA (
    ID_SERVICIO_ACTIVIDAD INT PRIMARY KEY,
    COSTO DECIMAL(10,2),
    METODO_PAGO CHAR(1),
    CONSTRAINT FK_Cuota_Serv FOREIGN KEY (ID_SERVICIO_ACTIVIDAD) REFERENCES OPERACION.SERVICIOS_ACTIVIDADES(ID_SERVICIO_ACTIVIDAD),
    CONSTRAINT CK_MetodoPagoCuota CHECK (METODO_PAGO IN ('T', 'E'))
);

-- TABLA 14: GRATUITAS
-- Descripción: Subtipo de actividad gratuita.
CREATE TABLE OPERACION.GRATUITAS (
    ID_SERVICIO_ACTIVIDAD INT PRIMARY KEY,
    ES_CULTURAL BIT,
    CONSTRAINT FK_Grat_Serv FOREIGN KEY (ID_SERVICIO_ACTIVIDAD) REFERENCES OPERACION.SERVICIOS_ACTIVIDADES(ID_SERVICIO_ACTIVIDAD)
);

-- TABLA 15: EMPLEADO_SERVICIO.
CREATE TABLE OPERACION.EMPLEADO_SERVICIO (
    ID_USUARIO INT,
    ID_SERVICIO_ACTIVIDAD INT,
    NOMBRE_EMPLEADO VARCHAR(100), 
    PRIMARY KEY (ID_USUARIO, ID_SERVICIO_ACTIVIDAD),
    CONSTRAINT FK_ES_Emp FOREIGN KEY (ID_USUARIO) REFERENCES MEMBRESIA.EMPLEADO(ID_USUARIO),
    CONSTRAINT FK_ES_Serv FOREIGN KEY (ID_SERVICIO_ACTIVIDAD) REFERENCES OPERACION.SERVICIOS_ACTIVIDADES(ID_SERVICIO_ACTIVIDAD)
);

-- TABLA 16: HORARIO
-- Descripción: Malla de horarios.
CREATE TABLE OPERACION.HORARIO (
    ID_HORARIO INT PRIMARY KEY IDENTITY(1,1),
    ID_SERVICIO_ACTIVIDAD INT,
    ID_INSTALACION VARCHAR(20),
    ID_PROFESOR INT, 
    DIA_SEMANA VARCHAR(15),
    HORA_INICIO TIME,
    HORA_FIN TIME,
    CONSTRAINT FK_Hor_Act FOREIGN KEY (ID_SERVICIO_ACTIVIDAD) REFERENCES OPERACION.SERVICIOS_ACTIVIDADES(ID_SERVICIO_ACTIVIDAD),
    CONSTRAINT FK_Hor_Inst FOREIGN KEY (ID_INSTALACION) REFERENCES OPERACION.INSTALACION(ID_INSTALACION),
    CONSTRAINT FK_Hor_Prof FOREIGN KEY (ID_PROFESOR) REFERENCES MEMBRESIA.EMPLEADO(ID_USUARIO)
);

-- TABLA 17: ENTRENAMIENTO
-- Descripción: Cabecera del plan de entrenamiento del socio.
CREATE TABLE OPERACION.ENTRENAMIENTO (
    ID_ENTRENAMIENTO INT PRIMARY KEY IDENTITY(1,1),
    ID_USUARIO INT,
    DIA_SEMANA VARCHAR(15),
    HORA_INICIO TIME,
    DURACION_MINUTOS INT,
    CONSTRAINT FK_Entreno_Socio FOREIGN KEY (ID_USUARIO) REFERENCES MEMBRESIA.SOCIO(ID_USUARIO)
);

-- TABLA 18: EJERCICIO_ENTRENAMIENTO
-- Descripción: Detalle del plan (ejercicios específicos).
CREATE TABLE OPERACION.EJERCICIO_ENTRENAMIENTO (
    ID_ENTRENAMIENTO INT,
    ID_EJERCICIO INT,
    SERIES_REALES INT,
    REPETICIONES INT,
    PRIMARY KEY (ID_ENTRENAMIENTO, ID_EJERCICIO),
    CONSTRAINT FK_EE_Plan FOREIGN KEY (ID_ENTRENAMIENTO) REFERENCES OPERACION.ENTRENAMIENTO(ID_ENTRENAMIENTO),
    CONSTRAINT FK_EE_Ejer FOREIGN KEY (ID_EJERCICIO) REFERENCES OPERACION.EJERCICIO(ID_EJERCICIO)
);

-- TABLA 19: INSCRIPCION
-- Descripción: Registro de un socio a una clase en un horario.
CREATE TABLE OPERACION.INSCRIPCION (
    ID_INSCRIPCION INT PRIMARY KEY IDENTITY(1,1),
    ID_USUARIO INT,
    ID_HORARIO INT,
    FECHA_INSCRIPCION DATETIME DEFAULT GETDATE(),
    ESTADO_INSCRIPCION VARCHAR(15) NOT NULL, 
    CONSTRAINT FK_Ins_Socio FOREIGN KEY (ID_USUARIO) REFERENCES MEMBRESIA.SOCIO(ID_USUARIO),
    CONSTRAINT FK_Ins_Horario FOREIGN KEY (ID_HORARIO) REFERENCES OPERACION.HORARIO(ID_HORARIO),
    CONSTRAINT CK_EstadoIns CHECK (ESTADO_INSCRIPCION IN ('SOLICITADA', 'PAGADA', 'CANCELADA'))
);

-- TABLA 20: ALQUILER
-- Descripción: Reservación de espacios físicos y materiales.
CREATE TABLE OPERACION.ALQUILER (
    ID_RESERVACION INT PRIMARY KEY IDENTITY(1,1),
    ID_USUARIO INT NOT NULL,
    ID_INSTALACION VARCHAR(20) NOT NULL,
    ID_MATERIAL VARCHAR(20) NULL,
    FECHA DATE NOT NULL,
    HORA_INICIO TIME NOT NULL,
    HORA_FIN TIME NOT NULL,
    NUMERO_PERSONAS INT,
    ESTADO_ALQUILER VARCHAR(20) NOT NULL, 
    CONSTRAINT FK_Alq_Socio FOREIGN KEY (ID_USUARIO) REFERENCES MEMBRESIA.SOCIO(ID_USUARIO),
    CONSTRAINT FK_Alq_Inst FOREIGN KEY (ID_INSTALACION) REFERENCES OPERACION.INSTALACION(ID_INSTALACION),
    CONSTRAINT FK_Alq_Mat FOREIGN KEY (ID_MATERIAL) REFERENCES OPERACION.MATERIAL(ID_MATERIAL),
    CONSTRAINT CK_EstadoAlq CHECK (ESTADO_ALQUILER IN ('SOLICITADO', 'ENTREGADO', 'DEVUELTO', 'DAÑADO', 'NO_ASISTIO'))
);


-- TABLA 21: PAGOS
-- Descripción: Registro financiero.
CREATE TABLE OPERACION.PAGOS (
    ID_PAGO INT PRIMARY KEY IDENTITY(1,1),
    ID_USUARIO INT,
    ID_INSCRIPCION INT NULL,
    MONTO DECIMAL(10,2) NOT NULL,
    FECHA_PAGO DATE DEFAULT GETDATE(),
    METODO_PAGO VARCHAR(20),
    BANCO VARCHAR(50),
    NUM_TARJETA VARCHAR(20),
    VIGENCIA_MES INT,
    VIGENCIA_ANIO INT,
    TIPO_CONCEPTO VARCHAR(20),
    CONSTRAINT FK_Pago_Socio FOREIGN KEY (ID_USUARIO) REFERENCES MEMBRESIA.SOCIO(ID_USUARIO),
    CONSTRAINT FK_Pago_Ins FOREIGN KEY (ID_INSCRIPCION) REFERENCES OPERACION.INSCRIPCION(ID_INSCRIPCION),
    
    CONSTRAINT CK_FechaPago CHECK (DAY(FECHA_PAGO) <= 5)
);

