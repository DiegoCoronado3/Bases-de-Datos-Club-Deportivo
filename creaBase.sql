-- TABLA 7: EJERCICIO
-- Descripción: Catálogo de ejercicios para entrenamientos.
CREATE TABLE OPERACION.EJERCICIO (
    ID_EJERCICIO INT PRIMARY KEY IDENTITY(1,1),
