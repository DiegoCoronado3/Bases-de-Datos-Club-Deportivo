-- TABLA 1: USUARIO_WEB
-- Descripción: Tabla padre que almacena credenciales y datos generales.
-- Consideración: Uso de IDENTITY (Llave Artificial) y UNIQUE.
CREATE TABLE MEMBRESIA.USUARIO_WEB (
    ID_USUARIO INT PRIMARY KEY IDENTITY(1,1),
    NOMBRE VARCHAR(50) NOT NULL,
    APELLIDO_P VARCHAR(50) NOT NULL,
    APELLIDO_M VARCHAR(50),
    CALLE VARCHAR(100) NOT NULL,
    NUMERO VARCHAR(20) NOT NULL,
    COLONIA VARCHAR(100) NOT NULL,
    ALCALDIA VARCHAR(100) NOT NULL,
    USUARIO VARCHAR(50) UNIQUE NOT NULL, -- Restricción UNIQUE
    CONTRASEÑA VARCHAR (100) NOT NULL, 
    FECHA_REGISTRO DATETIME DEFAULT GETDATE() -- Valor por DEFAULT 
);




ALTER TABLE MEMBRESIA.USUARIO_WEB
