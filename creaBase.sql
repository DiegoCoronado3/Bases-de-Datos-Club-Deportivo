-- TABLA 8: PLATILLO
-- Descripción: Catálogo de alimentos para dietas.
CREATE TABLE OPERACION.PLATILLO (
    ID_PLATILLO INT PRIMARY KEY IDENTITY(1,1),
    NOMBRE VARCHAR(50),
    DESCRIPCION_PREPARACION VARCHAR(MAX),
