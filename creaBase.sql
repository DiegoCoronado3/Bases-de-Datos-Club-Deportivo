GO


-- TABLA 2: SOCIO
-- Descripción: Subtipo de usuario. Maneja datos específicos de membresía.
-- Reglas: Validación de edad, tipo de membresía y estatus.
CREATE TABLE MEMBRESIA.SOCIO (
    ID_USUARIO INT PRIMARY KEY,
    NUM_SOCIO INT UNIQUE NOT NULL, -- Identificador alterno único
    TIPO_MEMBRESIA CHAR(1) NOT NULL, 
    FECHA_SOCIO DATE DEFAULT GETDATE(),
    IMAGEN_SOCIO VARBINARY(MAX),
    FECHA_NACIMIENTO DATE,
    ESTADO_SOCIO CHAR(1) NOT NULL,
    SEXO CHAR(1),
    PESO DECIMAL(5,2),
    ESTATURA DECIMAL(5,2),
    EDAD AS DATEDIFF(YEAR, FECHA_NACIMIENTO, GETDATE()), -- Columna Calculada
    
    CONSTRAINT FK_Socio_Usuario FOREIGN KEY (ID_USUARIO) REFERENCES MEMBRESIA.USUARIO_WEB(ID_USUARIO),
    -- Validación de Dominio (Check Constraints)
    CONSTRAINT CK_Membresia CHECK (TIPO_MEMBRESIA IN ('V', 'E')), -- V=VIP, E=Estándar
    CONSTRAINT CK_EstadoSocio CHECK (ESTADO_SOCIO IN ('A', 'C')), -- A=Adeudo, C=Corriente

    CONSTRAINT CK_EdadMinimaSocio CHECK (DATEDIFF(YEAR, FECHA_NACIMIENTO, GETDATE()) >= 16)
);


CREATE TABLE MEMBRESIA.TIPO_MEMBRESIA (
    TIPO_MEMBRESIA CHAR(1) PRIMARY KEY,  -- 'V' o 'E'
    NOMBRE VARCHAR(50),
    COSTO DECIMAL(10,2) NOT NULL
);

ALTER TABLE MEMBRESIA.SOCIO
ADD CONSTRAINT FK_Membresia_Tipo
FOREIGN KEY (TIPO_MEMBRESIA)
REFERENCES MEMBRESIA.TIPO_MEMBRESIA(TIPO_MEMBRESIA);




-- TABLA 3: EMPLEADO
-- Descripción: Subtipo de usuario para personal del club.
CREATE TABLE MEMBRESIA.EMPLEADO (
